package Basics;

public class Varibles {
    public static void main(String[] args) {
        int _x = 10; // Declare and initialize variable x
        System.out.println("The value of x is: " + _x);

        int y; // Declare variable y without initializing
        y = 20; // Initialize variable y after declaration
        System.out.println("The value of y is: " + y);
    }
}
